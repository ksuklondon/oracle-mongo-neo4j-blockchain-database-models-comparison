-- H.5 Complete order = JOIN of four tables
SELECT z.id_zamowienia, z.data_zamowienia, z.status,
       k.imie, k.nazwisko,
       p.nazwa, pz.ilosc, pz.cena,
       pz.ilosc * pz.cena AS wartosc_pozycji
FROM   zamowienia z
JOIN   klienci k           ON k.id_klienta    = z.id_klienta
JOIN   pozycje_zamowien pz ON pz.id_zamowienia = z.id_zamowienia
JOIN   produkty p          ON p.id_produktu    = pz.id_produktu
ORDER  BY z.id_zamowienia, p.nazwa;
