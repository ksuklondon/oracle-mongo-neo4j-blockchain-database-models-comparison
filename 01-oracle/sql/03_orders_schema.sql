-- =====================================================================
-- 03_orders_schema.sql  -  order management schema with declarative integrity
-- Requires CREATE SEQUENCE (IDENTITY columns) and CREATE TRIGGER for bd_lab.
-- =====================================================================

CREATE TABLE klienci (
    id_klienta  NUMBER GENERATED BY DEFAULT AS IDENTITY,
    imie        VARCHAR2(50)  NOT NULL,
    nazwisko    VARCHAR2(50)  NOT NULL,
    email       VARCHAR2(100) NOT NULL,
    CONSTRAINT pk_klienci       PRIMARY KEY (id_klienta),
    CONSTRAINT uq_klienci_email UNIQUE (email)
);

CREATE TABLE produkty (
    id_produktu     NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nazwa           VARCHAR2(100) NOT NULL,
    cena            NUMBER(10,2)  NOT NULL,
    stan_magazynowy NUMBER        DEFAULT 0 NOT NULL,
    CONSTRAINT pk_produkty      PRIMARY KEY (id_produktu),
    CONSTRAINT ck_produkty_cena CHECK (cena > 0),
    CONSTRAINT ck_produkty_stan CHECK (stan_magazynowy >= 0)
);

CREATE TABLE zamowienia (
    id_zamowienia   NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_klienta      NUMBER       NOT NULL,
    data_zamowienia DATE         DEFAULT SYSDATE NOT NULL,
    status          VARCHAR2(20) DEFAULT 'NOWE' NOT NULL,
    CONSTRAINT pk_zamowienia         PRIMARY KEY (id_zamowienia),
    CONSTRAINT fk_zamowienia_klient  FOREIGN KEY (id_klienta) REFERENCES klienci (id_klienta)
);

CREATE TABLE pozycje_zamowien (
    id_zamowienia NUMBER       NOT NULL,
    id_produktu   NUMBER       NOT NULL,
    ilosc         NUMBER       NOT NULL,
    cena          NUMBER(10,2) NOT NULL,
    CONSTRAINT pk_pozycje           PRIMARY KEY (id_zamowienia, id_produktu),
    CONSTRAINT fk_pozycje_zamowienie FOREIGN KEY (id_zamowienia) REFERENCES zamowienia (id_zamowienia),
    CONSTRAINT fk_pozycje_produkt    FOREIGN KEY (id_produktu)   REFERENCES produkty (id_produktu),
    CONSTRAINT ck_pozycje_ilosc      CHECK (ilosc > 0)
);

